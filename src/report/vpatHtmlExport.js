/* ─── Helpers ────────────────────────────────────────────────────────────────── */

function esc(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function nlToBr(str) {
  return esc(str).replace(/\n/g, '<br>')
}

/** Convert English criterion name to WCAG 2.2 URL fragment slug */
function criterionSlug(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
}

function conformanceBadge(level, t) {
  const label = t.conformance[level] ?? level
  const cls = {
    'supports':           'cl-supports',
    'partially-supports': 'cl-partial',
    'does-not-support':   'cl-no',
    'not-applicable':     'cl-na',
    'not-evaluated':      'cl-ne',
  }[level] ?? 'cl-ne'
  return `<span class="cl ${cls}">${esc(label)}</span>`
}

/* ─── WCAG table section ─────────────────────────────────────────────────────── */

function wcagPrincipleTable(principle, tableNum, vpatCriteria, t, lang) {
  const criteria = wcag22.filter(c => c.principle === principle)
  const princLabel = t.principles[principle]
  const tableId = `table-${principle.toLowerCase()}`

  const rows = criteria.map(c => {
    const entry   = vpatCriteria?.[c.id] ?? {}
    const level   = entry.conformanceLevel ?? 'not-evaluated'
    const remarks = entry.remarks?.trim() || ''
    const slug    = criterionSlug(c.name)
    const wcagUrl = `https://www.w3.org/TR/WCAG22/#${slug}`
    const critName = lang === 'sv' ? c.nameSwedish : c.name

    return `
        <tr>
          <td class="td-criteria">
            <a href="${wcagUrl}" target="_blank" rel="noreferrer">${esc(c.id)}: ${esc(critName)}</a>
            <span class="level-badge level-${c.level.toLowerCase()}" aria-label="${esc(t.level)} ${esc(c.level)}">${esc(c.level)}</span>
          </td>
          <td class="td-level">${conformanceBadge(level, t)}</td>
          <td class="td-remarks">${remarks ? nlToBr(remarks) : '<span class="empty-cell">—</span>'}</td>
        </tr>`
  }).join('')

  return `
    <div class="table-block">
      <h3 id="${tableId}">${esc(t.tablePrefix)} ${tableNum}: ${esc(princLabel)}</h3>
      <table aria-labelledby="${tableId}">
        <caption class="sr-only">${esc(t.tablePrefix)} ${tableNum}: ${esc(princLabel)}</caption>
        <thead>
          <tr>
            <th scope="col" class="th-criteria">${esc(t.colCriteria)}</th>
            <th scope="col" class="th-level">${esc(t.colConformance)}</th>
            <th scope="col" class="th-remarks">${esc(t.colRemarks)}</th>
          </tr>
        </thead>
        <tbody>${rows}
        </tbody>
      </table>
    </div>`
}

