/* ─── EN 301 549 Chapter 12 table ────────────────────────────────────────────── */

function en301549Chapter12(eaaStatus, t) {
  const rows = eaaRequirements.map(req => {
    const s         = eaaStatus?.[req.id] ?? { checkedItems: [] }
    const checked   = s.checkedItems.length
    const total     = req.checkItems.length
    const allDone   = total > 0 && checked === total
    const noneDone  = checked === 0
    const pct       = total > 0 ? Math.round((checked / total) * 100) : 0

    let statusLabel, statusCls
    if (allDone)       { statusLabel = t.statusFulfilled;    statusCls = 'cl-supports' }
    else if (noneDone) { statusLabel = t.statusNotEvaluated; statusCls = 'cl-ne' }
    else               { statusLabel = t.statusPartial;      statusCls = 'cl-partial' }

    const note = s.note?.trim() || ''

    return `
        <tr>
          <td class="td-criteria">
            <strong>${esc(req.id)}</strong>
            <span class="clause-name">${esc(req.title)}</span>
            <span class="ch12-pct">${pct}% (${checked}/${total})</span>
          </td>
          <td class="td-level"><span class="cl ${statusCls}">${esc(statusLabel)}</span></td>
          <td class="td-remarks">${note ? nlToBr(note) : '<span class="empty-cell">—</span>'}</td>
        </tr>`
  }).join('')

  return `
    <div class="table-block">
      <h3 id="ch12">${esc(t.ch12Title)}</h3>
      <p class="table-note">${esc(t.ch12Note)}</p>
      <table aria-labelledby="ch12">
        <caption class="sr-only">${esc(t.ch12Title)}</caption>
        <thead>
          <tr>
            <th scope="col" class="th-criteria">${esc(t.colRequirement)}</th>
            <th scope="col" class="th-level">${esc(t.colStatus)}</th>
            <th scope="col" class="th-remarks">${esc(t.colRemarks)}</th>
          </tr>
        </thead>
        <tbody>${rows}
        </tbody>
      </table>
    </div>`
}

